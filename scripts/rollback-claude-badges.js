const DRY = process.argv.includes('--dry');

const run = async () => {
  const before = await query('SELECT COUNT(*)::int AS n FROM product_badges');
  const libBefore = await query('SELECT COUNT(*)::int AS n FROM badges');
  console.log('до: связей ' + before.rows[0].n + ', бейджей в библиотеке ' + libBefore.rows[0].n);
  if (DRY) console.log('=== ПРОГОН БЕЗ УДАЛЕНИЯ ===');

  let removed = 0;
  let missing = 0;
  for (const [productId, badgeId] of CREATED_BY_SCRIPT) {
    const found = await query('SELECT 1 FROM product_badges WHERE product_id = $1 AND badge_id = $2', [productId, badgeId]);
    if (found.rows.length === 0) { console.log('уже нет такой связи: ' + productId + ' / ' + badgeId); missing += 1; continue; }
    if (!DRY) await query('DELETE FROM product_badges WHERE product_id = $1 AND badge_id = $2', [productId, badgeId]);
    removed += 1;
  }
  console.log('удалено связей: ' + removed + (missing ? ', не найдено: ' + missing : ''));

  // Контроль: ручные назначения на месте, библиотека цела.
  let survived = 0;
  const lost = [];
  for (const [productId, badgeId] of MUST_SURVIVE) {
    const f = await query('SELECT 1 FROM product_badges WHERE product_id = $1 AND badge_id = $2', [productId, badgeId]);
    if (f.rows.length) survived += 1; else lost.push(productId + ' / ' + badgeId);
  }
  console.log('ручных назначений на месте: ' + survived + ' из ' + MUST_SURVIVE.length);
  if (lost.length) console.log('ПОТЕРЯНО: ' + lost.join('; '));

  const after = await query('SELECT COUNT(*)::int AS n FROM product_badges');
  const libAfter = await query('SELECT COUNT(*)::int AS n FROM badges');
  console.log('после: связей ' + after.rows[0].n + ', бейджей в библиотеке ' + libAfter.rows[0].n);
  console.log('удалено бейджей из библиотеки: ' + (libBefore.rows[0].n - libAfter.rows[0].n));
  await pool.end();
};

run().catch((e) => { console.error('ОШИБКА:', e); process.exitCode = 1; });
