-- Витринная сводка состава набора для блока «Что внутри набора» на странице
-- товара: до пяти карточек вида «Овощи · 12 видов».
--
-- Почему отдельное поле, а не вычисление на лету. Настоящий состав лежит в
-- products.composition — массив пар [название, количество] («Картофель»,
-- «3 кг»). Категории у позиции там нет, поэтому посчитать «сколько овощей»
-- можно только сопоставлением названия со словарём, а словарь неизбежно
-- ошибается на пограничных случаях (шампиньоны — овощ? ягоды в каталоге
-- вообще не отдельная категория). Считать такое молча и показывать
-- покупателю как факт нельзя, поэтому у набора должна быть возможность
-- поправить сводку руками.
--
-- Почему колонка, а не таблица: это витрина из максимум пяти строк, которая
-- читается всегда целиком и вместе с товаром. Отдельная таблица добавила бы
-- join к каждому запросу каталога ради пяти чисел.
--
-- Формат — массив объектов, до пяти штук:
--   [{"key":"vegetables","label":"Овощи","count":12},
--    {"key":"other","label":"Ещё продуктов","count":3}]
-- key — id категории каталога (по нему фронт берёт картинку категории, тем
-- же приёмом, что кружки на Главной) либо "other" для последней карточки.
--
-- NULL или пустой массив — не «нет данных», а «считай сам»: фронт выводит
-- дефолт из composition по словарю (см. contentsSummary в format.js).
-- Поэтому поле nullable и без дефолта, и наборы, которым его не заполняли,
-- продолжают работать как раньше.
--
-- Применить: node migrations/apply.js 055_product_contents_summary.sql

BEGIN;

ALTER TABLE products ADD COLUMN IF NOT EXISTS contents_summary JSONB;

COMMIT;
