-- Продажная цена за килограмм для покупателя — витринный акцент вроде
-- "39 ₽/кг" (Ozon-style) для товаров с фиксированным весом (арбузы, дыни:
-- вес задаёт админ, покупатель ничего не выбирает). НЕ путать с
-- purchase_price (закупка, себестоимость, migrations/033/036) — это
-- розничная, customer-facing цена.
--
-- weight_kg (migrations/036) переиспользуется как есть: физический вес
-- упаковки один и тот же и для расчёта себестоимости, и для расчёта price
-- по price_per_kg (price = price_per_kg × weight_kg, считает админка) —
-- дублировать вес незачем. Осмысленно только при pricing_unit = 'kg' —
-- тот же гейт, что уже используется для weight_kg.
--
-- NULL (по умолчанию) — товар без акцента "цена за кг", отображение как
-- сейчас (просто price). Существующая price при этом не меняется и не
-- заменяется — price_per_kg лишь ДОПОЛНИТЕЛЬНЫЙ способ ввода/показа цены.
--
-- Применить: node migrations/apply.js 045_product_price_per_kg.sql

ALTER TABLE products ADD COLUMN IF NOT EXISTS price_per_kg NUMERIC CHECK (price_per_kg > 0);
