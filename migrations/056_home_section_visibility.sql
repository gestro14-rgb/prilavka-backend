-- Видимость витрин Главной: возможность временно убрать блок с витрины, не
-- трогая его состав.
--
-- Почему settings, а не новая таблица. Это одна строка на блок и один
-- булев флаг — ровно то, для чего settings и заведена (там же живут
-- заголовки «Сейчас в сезоне» и «Сегодня на прилавке», минимальный заказ,
-- проценты баллов). Отдельная таблица под пять значений добавила бы join к
-- каждому запросу /api/catalog и второй механизм настроек рядом с
-- существующим. Ручка PUT /api/admin/settings/:key уже умеет их править,
-- админке не нужен новый эндпоинт.
--
-- Почему НЕ в home_product_shelves. Там лежит состав витрины: строка =
-- товар в блоке. Флаг видимости относится к блоку целиком, и хранить его
-- рядом с товарами значило бы либо дублировать в каждой строке, либо
-- заводить строку-пустышку без товара. Кроме того, блок может быть скрыт
-- при непустом составе и наоборот — это независимые состояния, и смешивать
-- их нельзя: выключение не должно приводить к удалению товаров.
--
-- Ключи совпадают с ключами витрин (shelf в home_product_shelves) и с
-- вкладками админки: bundles, special, seasonal, hits.
--
-- Значение — текст 'true' | 'false', как у остальных настроек (колонка
-- value текстовая). Бэкенд читает через isHomeSectionVisible: всё, что не
-- равно строке 'false', считается «показывать». Поэтому отсутствие строки
-- (прод до применения этой миграции, блок, добавленный позже) означает
-- видимый блок, и после деплоя Главная не меняется, пока администратор
-- явно что-то не выключит.
--
-- ON CONFLICT DO NOTHING: миграцию можно применить повторно, уже
-- выставленные администратором значения не перетираются.
--
-- Применить: node migrations/apply.js 056_home_section_visibility.sql

BEGIN;

INSERT INTO settings (key, value, description) VALUES
  ('home_section_bundles_visible', 'true', 'Показывать блок «Готовые наборы» на Главной'),
  ('home_section_special_visible', 'true', 'Показывать блок «Сегодня на прилавке» на Главной'),
  ('home_section_seasonal_visible', 'true', 'Показывать блок «Сейчас в сезоне» на Главной'),
  ('home_section_hits_visible', 'true', 'Показывать блок «Хиты недели» на Главной')
ON CONFLICT (key) DO NOTHING;

COMMIT;
