--
-- До этого география жила прямо в названии («Арбуз, Дагестан», «Лимоны, ЮАР»)
-- — её нельзя было ни показать отдельной строкой, ни отредактировать, не
-- переписывая название. Поля под это не было: suppliers.region описывает
-- хозяйство-поставщика, а не происхождение продукта, и заполнено у одного
-- товара из 82.
--
-- Простая текстовая колонка, без справочника регионов: значения свободные
-- и разноуровневые («Краснодар», «Ростовская область», «ЮАР», «Крым»),
-- нормализовать их не во что, а связей и фильтров по региону в проекте нет.
-- Появится потребность фильтровать — справочник добавим тогда.
--
-- NULL = происхождение не указано. Наборов это поле не касается.
