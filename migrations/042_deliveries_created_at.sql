-- Автоматическая дата для "Последние доставки" на Главной (см. Home.jsx).
-- Раньше даты как таковой не было вообще — админ вписывал её вручную
-- текстом в поле "Текст" (например "Митино · вчера"), поэтому запись
-- выглядела "статичной", если текст не обновляли. created_at проставляется
-- автоматически при создании записи и не трогается при редактировании —
-- дата остаётся датой реального добавления записи.
--
-- Применить: node migrations/apply.js 042_deliveries_created_at.sql

ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();
