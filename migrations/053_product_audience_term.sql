-- Явные поля «на скольких человек» и «на какой срок» у набора — те самые две
-- строки, что стоят рядом с весом на hero-карточке Главной (👥 / 📅).
--
-- До этой миграции фронт добывал их регуляркой из названия и card_subtitle
-- (setPeopleLabel/setTermLabel в format.js): «Набор семейный для двоих на
-- неделю» → «Для двоих» / «На неделю». Это работало, но добывать факт из
-- названия можно только тот, который в названии уже написан — задать
-- «1-2 человека» или «на 5-7 дней», не переписывая при этом само название
-- товара (а оно уходит в чек заказа, поиск и историю «Уже заказывали»),
-- было нельзя. Отсюда отдельные поля: аудитория и срок — это данные о
-- товаре, а не побочный продукт его имени.
--
-- Регулярки в format.js остаются как запасной путь для наборов, которым эти
-- поля ещё не заполнили: пусто → фронт по-прежнему пробует достать фразу из
-- названия, и hero-карточка не пустеет (см. heroSets в Home.jsx).
--
-- Текст кладётся на экран ДОСЛОВНО, без правки регистра — в отличие от
-- регулярочного пути, который приводил вырезанный из середины фразы
-- фрагмент к виду подписи. Поэтому «1-2 человека» с заглавной, а
-- «на 5-7 дней» со строчной — так и задумано, это две разные по смыслу
-- строки: первая отвечает «сколько нас», вторая «насколько хватит».
--
-- Применить: node migrations/apply.js 053_product_audience_term.sql

BEGIN;

ALTER TABLE products ADD COLUMN IF NOT EXISTS audience_label TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS term_label     TEXT;

-- Набор, который сейчас стоит в hero Главной (единственный с
-- home_video_url). Значения согласуются с уже имеющимися данными товара, а
-- не противоречат им: в названии «для двоих» — отсюда «1-2 человека»,
-- «на неделю» — отсюда «на 5-7 дней». Вес (~11 кг) не трогаем, он приходит
-- из products.weight и рисуется отдельной строкой между ними.
--
-- WHERE ... IS NULL — повторный прогон не затрёт правку из админки.
UPDATE products
   SET audience_label = '1-2 человека'
 WHERE id = '499494' AND audience_label IS NULL;

UPDATE products
   SET term_label = 'на 5-7 дней'
 WHERE id = '499494' AND term_label IS NULL;

COMMIT;
