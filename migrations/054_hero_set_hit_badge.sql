-- Бейдж hero-набора: 'deal' («Выгодно») → 'hit' («🔥 Хит»).
--
-- Данные, а не вёрстка: набор 499494 («Набор семейный для двоих на неделю»)
-- — самый часто заказываемый, и на Главной он должен читаться как хит, а не
-- как разовая скидка. Скидка у него при этом никуда не делась и остаётся
-- видна ценой: old_price 3 290 → price 2 990, зачёркнутая цена и чип −9%
-- рисуются из этих полей независимо от бейджа.
--
-- badge_label тоже переписан, хотя фронт его для типа 'hit' игнорирует
-- (текст у «Хита» фиксированный — см. HitBadge.jsx): оставлять в базе
-- «Выгодно» у бейджа типа 'hit' значило бы оставить ловушку для того, кто
-- откроет карточку в админке.
--
-- badge_color обнулён: там лежал зелёный #1C8F1C от прежнего типа, а «Хит» —
-- единственный по-настоящему яркий бейдж и должен быть оранжевым по
-- умолчанию.
--
-- WHERE badge_type = 'deal' — миграция не воюет с админкой: если бейдж к
-- моменту повторного прогона уже поменяли руками, UPDATE ничего не тронет.
--
-- Применить: node migrations/apply.js 054_hero_set_hit_badge.sql

BEGIN;

UPDATE products
   SET badge_type  = 'hit',
       badge_label = 'Хит',
       badge_color = NULL
 WHERE id = '499494'
   AND badge_type = 'deal';

COMMIT;
