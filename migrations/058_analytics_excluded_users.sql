-- Пользователи, чьи события не учитываются в аналитике.
--
-- Зачем. Замер на живых данных: из 2370 сессий 648 принадлежат владельцу
-- магазина и ещё 492 — тестовому идентификатору стенда (user_id = 1).
-- Это 48% всех сессий и 55% всех событий. Любая метрика — посетители,
-- воронка, конверсия, популярные товары — считалась вместе с ними, то
-- есть показывала не покупателей, а владельца, который ходит по своему же
-- магазину.
--
-- Почему таблица, а не настройка в settings. Список должен уметь расти
-- (владелец, тестовые аккаунты, будущие сотрудники), у каждой записи своя
-- причина и свой выключатель, и по нему идёт JOIN/подзапрос в каждом
-- аналитическом запросе. Хранить это строкой с перечислением id в
-- settings пришлось бы парсить на каждый запрос и нечем было бы объяснить
-- в интерфейсе, кто есть кто.
--
-- Ключ — telegram_id, а НЕ users.id. Так устроена сама аналитика:
-- analytics_events.user_id — это Telegram user id, который присылает
-- мини-апп (см. комментарий у analyticsUserName в server.js). Часть
-- событий приходит вообще без опознанного пользователя, поэтому
-- исключение применяется по СЕССИИ: сессия отбрасывается целиком, если
-- хоть одно её событие принадлежит исключённому пользователю.
--
-- Исторические данные НЕ удаляются: события остаются в analytics_events
-- как были, меняется только то, что агрегаты их не считают. Выключить
-- исключение (is_active = false) — и цифры вернутся ровно те же.
--
-- Сразу заводим две записи:
--   686803005 — владелец магазина (Михаил, @mihsa1407): именно его сессии
--               и просил не учитывать;
--   1         — идентификатор автотестового стенда: реального аккаунта
--               Telegram с таким id не существует, все 492 его сессии
--               созданы проверками интерфейса.
-- Обе с is_active = true; убрать любую можно из админки.
--
-- Применить: node migrations/apply.js 058_analytics_excluded_users.sql

BEGIN;

CREATE TABLE IF NOT EXISTS analytics_excluded_users (
  telegram_id BIGINT PRIMARY KEY,
  -- Свободный текст, а не enum: список причин заранее не известен, а
  -- CHECK пришлось бы менять миграцией ради каждого нового типа.
  -- Договорённые значения: 'owner', 'admin', 'test'.
  reason      TEXT NOT NULL DEFAULT 'test',
  -- Заметка для человека: чей это аккаунт. Telegram id в интерфейсе не
  -- показываем (см. требование о приватности), показываем эту подпись.
  note        TEXT,
  is_active   BOOLEAN NOT NULL DEFAULT true,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO analytics_excluded_users (telegram_id, reason, note) VALUES
  (686803005, 'owner', 'Владелец магазина'),
  (1,         'test',  'Автотесты интерфейса')
ON CONFLICT (telegram_id) DO NOTHING;

COMMIT;
