-- Библиотека бейджей товара и их привязка к товарам.
--
-- Зачем таблица, а не колонки и не settings. Бейдж — это сущность со
-- своими полями (текст, эмодзи, два цвета, порядок, активность), список
-- которой ведёт администратор, плюс связь многие-ко-многим с товарами и
-- порядком внутри товара. Настройками такое не описать, а колонками в
-- products — только один бейдж на товар и без переиспользования между
-- товарами: смена цвета «Сочных» потребовала бы обойти все карточки.
--
-- Отношение к СТАРОЙ системе. products.badge_type / badge_label /
-- badge_color остаются нетронутыми и продолжают работать как работали.
-- Автоматической миграции данных нет намеренно: badge_type = 'hit'
-- участвует в подборе «Хитов недели» (см. hitProducts в Home.jsx), то
-- есть старый бейдж — наполовину классификатор, и переносить его в чисто
-- визуальную библиотеку значило бы молча поменять бизнес-логику. Новая
-- система — отдельный визуальный слой поверх, а не замена.
--
-- Отношение к тегам. tag_label / tag_color — тоже не трогаем: тег
-- отбирает товары в витрину «Сегодня на прилавке», это классификация, а
-- не оформление.
--
-- Ограничения на количество бейджей у товара в базе НЕТ: сколько
-- назначили, столько и хранится. Сколько показывать — решает карточка
-- (grid и bundle рисуют один, полка «Сегодня на прилавке» — ни одного,
-- страница товара — все активные).
--
-- ON DELETE CASCADE на обеих ссылках:
--   • удалили товар — его привязки уходят вместе с ним, как у reviews и
--     home_product_shelves (тот же паттерн, что уже принят в схеме);
--   • удалили бейдж из библиотеки — привязки уходят сами, и на карточках
--     не остаётся висячих ссылок. Сами товары при этом не трогаются.
--
-- Применить: node migrations/apply.js 057_product_badges.sql

BEGIN;

CREATE TABLE IF NOT EXISTS badges (
  id          SERIAL PRIMARY KEY,
  label       TEXT    NOT NULL,
  -- Эмодзи. NULL или пустая строка — бейдж без иконки, только текст.
  icon        TEXT,
  bg_color    TEXT    NOT NULL,
  text_color  TEXT    NOT NULL,
  -- Порядок в списке админки и запасной ключ сортировки на карточке.
  sort_order  INTEGER NOT NULL DEFAULT 0,
  -- Мягкое скрытие: выключенный бейдж остаётся в базе и у товаров, но не
  -- уходит в витрину. Нужен, чтобы убрать сезонную плашку и вернуть её
  -- через месяц, не пересоздавая и не теряя привязки.
  is_active   BOOLEAN NOT NULL DEFAULT true,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS product_badges (
  product_id  TEXT    NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  badge_id    INTEGER NOT NULL REFERENCES badges(id)   ON DELETE CASCADE,
  -- Порядок бейджей внутри товара: карточка, которая рисует один бейдж,
  -- берёт первый по этому полю.
  sort_order  INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (product_id, badge_id)
);

-- Каталог собирает бейджи одним запросом по всем товарам и раскладывает их
-- по product_id; индекс нужен под join к products, первичный ключ его не
-- закрывает только для обратного направления (выборка «у кого этот бейдж»
-- при удалении).
CREATE INDEX IF NOT EXISTS idx_product_badges_badge ON product_badges (badge_id);

COMMIT;
